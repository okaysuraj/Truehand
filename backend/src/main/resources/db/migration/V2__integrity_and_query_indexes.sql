-- Preserve financial and order history: foreign keys intentionally restrict deletion.
CREATE UNIQUE INDEX uq_users_email_normalized ON users (lower(email));
CREATE UNIQUE INDEX uq_users_firebase_uid ON users (firebase_uid) WHERE firebase_uid IS NOT NULL;
ALTER TABLE users ADD CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER', 'SELLER', 'DELIVERY', 'ADMIN'));
ALTER TABLE products ADD CONSTRAINT ck_products_price CHECK (price > 0);
ALTER TABLE products ADD CONSTRAINT ck_products_stock CHECK (stock_quantity >= 0);
ALTER TABLE products ADD CONSTRAINT ck_products_sale CHECK (sale_price IS NULL OR (sale_price > 0 AND sale_price < price AND sale_starts_at IS NOT NULL AND sale_ends_at > sale_starts_at));
ALTER TABLE products ADD CONSTRAINT ck_products_approval CHECK (approval_status IN ('PENDING', 'APPROVED', 'REJECTED', 'WITHDRAWN'));
ALTER TABLE product_variants ADD CONSTRAINT ck_variants_stock CHECK (stock_quantity >= 0);
ALTER TABLE product_variants ADD CONSTRAINT ck_variants_price CHECK (additional_price >= 0);
CREATE UNIQUE INDEX uq_variants_sku ON product_variants (sku) WHERE sku IS NOT NULL;
ALTER TABLE orders ADD CONSTRAINT ck_orders_amount CHECK (total_amount > 0);
ALTER TABLE orders ADD CONSTRAINT ck_orders_payment CHECK (payment_status IN ('PENDING', 'PAID', 'FAILED', 'REFUND_PENDING', 'REFUNDED'));
ALTER TABLE orders ADD CONSTRAINT ck_orders_status CHECK (status IN ('PENDING', 'CONFIRMED', 'PROCESSING', 'SHIPPED', 'OUT_FOR_DELIVERY', 'DELIVERED', 'CANCELLED', 'RETURN_REQUESTED', 'RETURNED'));
ALTER TABLE order_items ADD CONSTRAINT ck_order_items_quantity CHECK (quantity > 0);
ALTER TABLE order_items ADD CONSTRAINT ck_order_items_price CHECK (price_at_purchase > 0);
ALTER TABLE cart_items ADD CONSTRAINT ck_cart_items_quantity CHECK (quantity > 0 AND quantity <= 1000);
ALTER TABLE cart_items ADD CONSTRAINT ck_cart_items_price CHECK (price >= 0);
CREATE UNIQUE INDEX uq_cart_product ON cart_items (cart_id, product_id);
CREATE UNIQUE INDEX uq_wishlist_product ON wishlists (user_id, product_id);
ALTER TABLE reviews ADD CONSTRAINT ck_reviews_rating CHECK (rating >= 1 AND rating <= 5);
ALTER TABLE product_reviews ADD CONSTRAINT ck_product_reviews_rating CHECK (rating >= 1 AND rating <= 5);
CREATE UNIQUE INDEX uq_reviews_purchase ON reviews (user_id, product_id);
CREATE UNIQUE INDEX uq_product_reviews_user ON product_reviews (user_id, product_id);
ALTER TABLE wallets ADD CONSTRAINT ck_wallet_balance CHECK (balance >= 0);
ALTER TABLE wallet_transactions ADD CONSTRAINT ck_wallet_tx_amount CHECK (amount > 0);
ALTER TABLE wallet_transactions ADD CONSTRAINT ck_wallet_tx_type CHECK (type IN ('CREDIT', 'DEBIT'));
ALTER TABLE payout_requests ADD CONSTRAINT fk_payout_seller FOREIGN KEY (seller_id) REFERENCES users(id);
ALTER TABLE payout_requests ADD CONSTRAINT ck_payout_amount CHECK (amount > 0);
ALTER TABLE promo_codes ADD CONSTRAINT ck_promo_percentage CHECK (discount_percentage > 0 AND discount_percentage <= 100);
ALTER TABLE promo_codes ADD CONSTRAINT ck_promo_cap CHECK (max_discount_amount IS NULL OR max_discount_amount > 0);
ALTER TABLE locations ADD CONSTRAINT ck_location_latitude CHECK (latitude BETWEEN -90 AND 90);
ALTER TABLE locations ADD CONSTRAINT ck_location_longitude CHECK (longitude BETWEEN -180 AND 180);
ALTER TABLE locations ADD CONSTRAINT ck_location_accuracy CHECK (accuracy IS NULL OR accuracy >= 0);
CREATE UNIQUE INDEX uq_address_default ON addresses (user_id) WHERE is_default = true;
CREATE UNIQUE INDEX uq_bank_default ON bank_accounts (user_id) WHERE is_default = true;
CREATE UNIQUE INDEX uq_support_request_number ON support_requests (request_id);
CREATE INDEX idx_products_catalog ON products (category_id, price, id) WHERE is_available = true AND approval_status = 'APPROVED';
CREATE INDEX idx_products_seller ON products (seller_id, created_at DESC);
CREATE INDEX idx_product_search ON products USING gin (to_tsvector('simple', coalesce(name, '') || ' ' || coalesce(description, '')));
CREATE INDEX idx_orders_user_date ON orders (user_id, created_at DESC);
CREATE INDEX idx_orders_status_date ON orders (status, created_at DESC);
CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_order_items_product ON order_items (product_id, order_id);
CREATE INDEX idx_deliveries_agent_status ON deliveries (delivery_boy_id, status);
CREATE INDEX idx_locations_delivery_time ON locations (delivery_id, timestamp DESC);
CREATE INDEX idx_wallet_transactions_time ON wallet_transactions (wallet_id, created_at DESC);
CREATE INDEX idx_notifications_user_time ON notifications (user_id, created_at DESC);
CREATE INDEX idx_notifications_unread ON notifications (user_id) WHERE is_read = false;
CREATE INDEX idx_support_user ON support_requests (user_id, id DESC);
CREATE INDEX idx_support_order ON support_requests (order_id);
CREATE INDEX idx_questions_product ON questions (product_id, created_at DESC);
CREATE INDEX idx_reviews_product ON reviews (product_id, created_at DESC);
CREATE INDEX idx_artisan_posts_time ON artisan_posts (created_at DESC);
