-- TrueHand PostgreSQL baseline for a NEW, EMPTY database.
-- No seed data. Existing databases need a reviewed reconciliation before baselining.

CREATE TABLE addresses (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    label varchar(255) NOT NULL,
    street_address varchar(255) NOT NULL,
    city varchar(255) NOT NULL,
    state varchar(255) NOT NULL,
    postal_code varchar(255) NOT NULL,
    country varchar(255),
    full_name varchar(255),
    phone varchar(255),
    is_default BOOLEAN DEFAULT FALSE,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone
);

CREATE TABLE artisan_posts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artisan_id integer NOT NULL,
    content TEXT,
    media_url varchar(255),
    likes_count integer,
    created_at timestamp(6) without time zone
);

CREATE TABLE bank_accounts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    bank_name varchar(255) NOT NULL,
    account_type varchar(255) NOT NULL,
    last_four varchar(4) NOT NULL,
    is_default boolean NOT NULL,
    status varchar(255) NOT NULL,
    routing_number varchar(255) NOT NULL,
    account_name varchar(255) NOT NULL
);

CREATE TABLE carts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    total_amount numeric(19,2),
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone
);

CREATE TABLE cart_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id integer NOT NULL,
    product_id integer NOT NULL,
    quantity integer NOT NULL,
    price numeric(19,2) NOT NULL,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone
);

CREATE TABLE categories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE,
    description TEXT,
    image_url varchar(255),
    parent_id integer,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone
);

CREATE TABLE deliveries (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL,
    delivery_boy_id integer,
    status VARCHAR(50) DEFAULT 'PENDING',
    estimated_delivery_time timestamp(6) without time zone,
    actual_delivery_time timestamp(6) without time zone,
    delivery_distance_km numeric(19,2),
    otp_hash varchar(255),
    otp_issued_at timestamp(6) without time zone,
    otp_expires_at timestamp(6) without time zone,
    otp_attempts integer,
    otp_verified_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone
);

CREATE TABLE delivery_personnel (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    vehicle_type varchar(255),
    vehicle_registration_number varchar(255),
    driving_license_number varchar(255),
    kyc_status VARCHAR(50) DEFAULT 'PENDING',
    rejection_reason varchar(255),
    is_available boolean
);

CREATE TABLE delivery_routes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id integer NOT NULL,
    optimized_polyline varchar(255),
    total_distance_meters integer,
    estimated_duration_seconds integer,
    created_at timestamp(6) without time zone
);

CREATE TABLE fleet_vehicles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id integer NOT NULL,
    vehicle_registration_number varchar(255),
    vehicle_type varchar(255),
    current_lat double precision,
    current_lng double precision,
    last_ping_at timestamp(6) without time zone,
    status varchar(255)
);

CREATE TABLE locations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id integer NOT NULL,
    latitude DECIMAL(10, 8) NOT NULL,
    longitude DECIMAL(11, 8) NOT NULL,
    accuracy DECIMAL(10, 2),
    timestamp timestamp(6) without time zone
);

CREATE TABLE marketing_campaigns (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_name varchar(255),
    target_audience varchar(255),
    email_body TEXT,
    status varchar(255),
    sent_count integer,
    created_at timestamp(6) without time zone
);

CREATE TABLE notifications (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    title varchar(255),
    body varchar(255),
    type varchar(255),
    is_read boolean NOT NULL,
    created_at timestamp(6) without time zone
);

CREATE TABLE orders (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    order_number varchar(255) UNIQUE,
    total_amount numeric(19,2) NOT NULL,
    status VARCHAR(50) DEFAULT 'PENDING',
    address_id integer,
    delivery_address_snapshot TEXT,
    payment_status VARCHAR(50) DEFAULT 'PENDING',
    payment_intent_id varchar(255) UNIQUE,
    checkout_key varchar(255) UNIQUE,
    special_instructions TEXT,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone
);

CREATE TABLE order_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL,
    product_id integer NOT NULL,
    quantity integer NOT NULL,
    price_at_purchase numeric(19,2) NOT NULL,
    product_name_snapshot varchar(255),
    image_url_snapshot TEXT,
    created_at timestamp(6) without time zone
);

CREATE TABLE password_reset_tokens (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    token varchar(255),
    expiry_date timestamp(6) without time zone
);

CREATE TABLE payout_requests (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id integer NOT NULL,
    seller_name varchar(255) NOT NULL,
    amount numeric(19,2) NOT NULL,
    status varchar(255) NOT NULL,
    requested_at timestamp(6) without time zone,
    bank_account varchar(255),
    bank_account_id integer,
    request_key varchar(255) UNIQUE
);

CREATE TABLE platform_settings (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maintenance_mode boolean NOT NULL,
    maintenance_message varchar(255),
    registrations_enabled boolean NOT NULL,
    updated_at timestamp(6) without time zone
);

CREATE TABLE products (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    description TEXT,
    category_id integer,
    price numeric(19,2) NOT NULL,
    stock_quantity INT DEFAULT 0,
    image_url TEXT,
    is_available BOOLEAN DEFAULT TRUE,
    approval_status VARCHAR(255) DEFAULT 'APPROVED',
    sale_price numeric(19,2),
    sale_starts_at timestamp(6) without time zone,
    sale_ends_at timestamp(6) without time zone,
    seller_id integer,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    average_rating DOUBLE PRECISION DEFAULT 0.0,
    review_count INT DEFAULT 0
);

CREATE TABLE product_reviews (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL,
    user_id integer NOT NULL,
    rating integer,
    review_text varchar(255),
    image_url varchar(255),
    created_at timestamp(6) without time zone
);

CREATE TABLE product_variants (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL,
    sku varchar(255),
    size varchar(255),
    color varchar(255),
    additional_price numeric(19,2),
    stock_quantity INT DEFAULT 0,
    image_url varchar(255),
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone
);

CREATE TABLE promo_codes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(255) NOT NULL UNIQUE,
    discount_percentage numeric(19,2) NOT NULL,
    max_discount_amount numeric(19,2),
    valid_until timestamp(6) without time zone NOT NULL,
    is_active boolean NOT NULL
);

CREATE TABLE questions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL,
    user_id integer NOT NULL,
    content varchar(1000) NOT NULL,
    answer varchar(1000),
    created_at timestamp(6) without time zone
);

CREATE TABLE reviews (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL,
    product_id integer,
    user_id integer NOT NULL,
    rating integer,
    comment TEXT,
    created_at timestamp(6) without time zone
);

CREATE TABLE seller_profiles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
